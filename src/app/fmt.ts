/**
 * app/fmt.ts — 数字的显示形态。
 *
 * 只有一个函数：`abbr`（大数缩写），`12,800 → 1.3万` 的排版规则。
 */

/**
 * 大数缩写：`12,800 → 1.3万`、`250,000 → 25万`。
 *
 * 判据不是「小于多少万不缩写」，而是「**缩写不能撒谎**」：
 * `abbr(10,300)` 曾经返回「1万」—— 10,300 被报成 10,000，误差 3%，
 * 而且读起来像「基本没打」。`1.3万` 不是谎，`1.0万` 是。
 * 所以走的是**字符串判定**（`toFixed(1)` 之后是不是以 `.0` 结尾），
 * 不是数值区间：`9.995万` 会 toFixed 成 `10.0`，也落在同一条例外里。
 *
 * | 输入 | 输出 | 走哪条 |
 * |---|---|---|
 * | 8,600 | `8,600` | < 1 万，原样 |
 * | 10,300 | `10,300` | 1.03 → `1.0` 以 `.0` 结尾 → 精确值 |
 * | 10,800 | `1.1万` | 1.08 → `1.1` |
 * | 99,950 | `99,950` | 9.995 → `10.0` 以 `.0` 结尾 → 精确值 |
 * | 100,000 | `10万` | 10.0 被 strip |
 * | 1,234,567 | `123万` | ≥100 取整 |
 */
export function abbr(n: number): string {
  const v = Number.isFinite(n) ? Math.max(0, Math.floor(n)) : 0;
  if (v < 10000) return v.toLocaleString('zh-CN');
  const w = v / 10000;
  if (w < 10) {
    const one = w.toFixed(1);
    // `1.0` 是四舍五入的谎（10,300 报成 10,000）→ 退回精确值
    return one.endsWith('.0') ? v.toLocaleString('zh-CN') : `${one}万`;
  }
  // 100 万以上不留小数（「123万」比「123.4万」稳），10 万以上留一位
  const text = w >= 100 ? String(Math.round(w)) : w.toFixed(1).replace(/\.0$/, '');
  return `${text}万`;
}
